//! Lines a coding agent adds to say it wrote a commit: `Co-Authored-By: Claude
//! <noreply@anthropic.com>`, `🤖 Generated with [Claude Code](…)`, a session link.
//!
//! Squad Code keeps them only when **Credit the agent in commits** is on. Otherwise
//! Shipper takes them out of the job's commits before it pushes or merges, and out
//! of the squash message when it merges a pull request on GitHub. A person's own
//! co-author lines stay: only lines naming a coding agent go.

/// Agent names that mark a co-author line as an agent's. Matched as whole words
/// in the name before the address.
const NAMES: &[&str] = &[
    "claude",
    "codex",
    "gemini",
    "copilot",
    "cursor",
    "cursoragent",
    "amp",
    "droid",
    "qwen",
    "grok",
    "opencode",
    "devin",
    "aider",
    "jules",
    "antigravity",
    "kiro",
];

/// Addresses that mark a co-author line as an agent's, wherever the name says.
const ADDRESSES: &[&str] = &[
    "@anthropic.com",
    "@openai.com",
    "@ampcode.com",
    "@cursor.com",
    "@factory.ai",
    "@x.ai",
    "@opencode.ai",
    "copilot@users.noreply.github.com",
    "devin-ai-integration",
];

/// Products named in a "Generated with …" line.
const PRODUCTS: &[&str] = &[
    "claude code",
    "claude",
    "codex",
    "gemini",
    "copilot",
    "cursor",
    "opencode",
    "amp",
    "droid",
    "qwen",
    "grok",
    "devin",
    "aider",
];

fn words(s: &str) -> Vec<String> {
    s.to_lowercase()
        .split(|c: char| !c.is_alphanumeric())
        .filter(|w| !w.is_empty())
        .map(str::to_string)
        .collect()
}

/// Whether `line` credits a coding agent.
pub fn is_credit(line: &str) -> bool {
    let t = line
        .trim()
        .trim_matches(|c: char| c == '_' || c == '*')
        .trim();
    let lower = t.to_lowercase();
    if let Some(rest) = lower.strip_prefix("co-authored-by:") {
        let (name, address) = match rest.find('<') {
            Some(i) => (&rest[..i], &rest[i..]),
            None => (rest, ""),
        };
        let ws = words(name);
        return ws.iter().any(|w| NAMES.contains(&w.as_str()))
            || ADDRESSES.iter().any(|a| address.contains(a));
    }
    if lower.starts_with("claude-session:") || lower.contains("claude.ai/code") {
        return true;
    }
    let generated = [
        "generated with",
        "generated by",
        "made with",
        "created with",
    ]
    .iter()
    .any(|g| lower.contains(g));
    if generated {
        let ws = words(&lower).join(" ");
        return PRODUCTS
            .iter()
            .any(|p| format!(" {ws} ").contains(&format!(" {p} ")));
    }
    false
}

/// `msg` without the lines that credit a coding agent, and without the blank
/// lines and `---` rule they leave at its end. Unchanged when there are none.
pub fn strip(msg: &str) -> String {
    if !msg.lines().any(is_credit) {
        return msg.to_string();
    }
    let mut lines: Vec<&str> = msg.lines().filter(|l| !is_credit(l)).collect();
    while lines
        .last()
        .is_some_and(|l| l.trim().is_empty() || l.trim() == "---")
    {
        lines.pop();
    }
    let mut out = lines.join("\n");
    if msg.ends_with('\n') && !out.is_empty() {
        out.push('\n');
    }
    out
}

/// Whether `msg` has a line crediting a coding agent.
pub fn has(msg: &str) -> bool {
    msg.lines().any(is_credit)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn agent_trailers_and_footers_go() {
        let msg = "Fix the login redirect\n\nIt looped on Safari.\n\n\u{1f916} Generated with [Claude Code](https://claude.com/claude-code)\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nClaude-Session: https://claude.ai/code/session_1\n";
        assert_eq!(
            strip(msg),
            "Fix the login redirect\n\nIt looped on Safari.\n"
        );
        assert!(has(msg));
        assert!(!has(&strip(msg)));
    }

    #[test]
    fn other_agents_are_caught_by_name_or_address() {
        for line in [
            "Co-authored-by: Codex <codex@openai.com>",
            "Co-authored-by: Cursor Agent <cursoragent@cursor.com>",
            "Co-authored-by: Amp <amp@ampcode.com>",
            "Co-authored-by: factory-droid[bot] <138933559+factory-droid[bot]@users.noreply.github.com>",
            "Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>",
            "co-authored-by: gemini-code-assist",
            "_Generated by [Claude Code](https://claude.ai/code/session_1)_",
            "Generated with Codex",
        ] {
            assert!(is_credit(line), "{line}");
        }
    }

    #[test]
    fn people_and_ordinary_lines_stay() {
        for line in [
            "Co-authored-by: Ana Lima <ana@example.com>",
            "Co-authored-by: Sam Ampersand <sam@google.com>",
            "Generated with our own codegen script",
            "Fix the cursor position in the editor",
            "Signed-off-by: Ana Lima <ana@example.com>",
        ] {
            assert!(!is_credit(line), "{line}");
        }
        let msg = "Add a login page\n\nCo-authored-by: Ana Lima <ana@example.com>\n";
        assert_eq!(strip(msg), msg);
    }

    #[test]
    fn a_footer_rule_left_behind_goes_too() {
        let msg =
            "## Summary\n\nDone.\n\n---\n_Generated by [Claude Code](https://claude.ai/code/x)_";
        assert_eq!(strip(msg), "## Summary\n\nDone.");
    }
}
